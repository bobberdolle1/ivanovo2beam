"""Generate building geometry and write it as COLLADA.

BeamNG 0.39 loads plain ``.dae`` files directly: all 77,678 ``shapeName``
references across the shipped levels point at ``.dae``, and the compiled
``.cdae`` files beside them are caches, not a requirement. That makes generated
buildings possible without a binary mesh format writer.

Only the small part of COLLADA that BeamNG actually reads is emitted — one
geometry per file, flat-shaded triangles, a lambert colour material, ``Z_UP``
and metres. No textures are referenced, so nothing needs bundling.

Geometry
--------
A building is an extrusion of its real OSM footprint, optionally with a roof,
in a local frame centred on the footprint so that a single ``TSStatic``
``position`` places it. Walls get flat outward normals; roofs are generated by
triangulating the footprint and lifting each vertex as a function of its
position, which yields a correct gable or hip for an arbitrary plan shape
without special-casing rectangles.

Everything is deterministic: positions come from the footprint, and the COLLADA
timestamps are fixed, so two builds of the same level produce byte-identical
meshes.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING
from xml.sax.saxutils import escape

import numpy as np
from shapely import constrained_delaunay_triangles
from shapely.geometry import Point, Polygon, box

if TYPE_CHECKING:  # pragma: no cover - typing only
    from collections.abc import Callable

    from numpy.typing import NDArray

#: Fixed timestamp written into every generated DAE, so output is reproducible.
_FIXED_TIMESTAMP = "2026-01-01T00:00:00"

#: Roof pitch as a fraction of half the building depth.
_ROOF_PITCH = 0.35

#: Bounds on generated roof height, in metres.
_MIN_ROOF_M = 0.8
_MAX_ROOF_M = 4.5


@dataclass(slots=True)
class Mesh:
    """A flat-shaded triangle mesh with per-corner normals.

    Attributes:
        positions: Unique vertex positions.
        normals: Unique normal vectors.
        triangles: One entry per triangle, holding three ``(position, normal)``
            index pairs — the layout COLLADA's ``<p>`` element expects.
    """

    positions: list[tuple[float, float, float]] = field(default_factory=list)
    normals: list[tuple[float, float, float]] = field(default_factory=list)
    triangles: list[tuple[tuple[int, int], tuple[int, int], tuple[int, int]]] = field(
        default_factory=list
    )
    _position_index: dict[tuple[float, float, float], int] = field(
        default_factory=dict, repr=False, compare=False
    )
    _normal_index: dict[tuple[float, float, float], int] = field(
        default_factory=dict, repr=False, compare=False
    )

    def add_triangle(
        self,
        a: tuple[float, float, float],
        b: tuple[float, float, float],
        c: tuple[float, float, float],
    ) -> None:
        """Append a triangle, computing and sharing its flat normal.

        Positions are rounded *before* the degeneracy test, because the mesh is
        written with four decimal places. A sliver that is non-degenerate at full
        precision but collapses once rounded would otherwise be emitted as a
        triangle with two coincident corners — invisible, useless, and a
        plausible source of trouble in the engine's collision builder.

        Args:
            a: First corner position.
            b: Second corner position.
            c: Third corner position.
        """
        rounded = tuple(_round3(p) for p in (a, b, c))
        if len(set(rounded)) < 3:
            return
        normal = _face_normal(*rounded)
        if normal is None:
            return
        corners = tuple((self._vertex(p), self._normal(normal)) for p in rounded)
        self.triangles.append(corners)  # type: ignore[arg-type]

    def _vertex(self, position: tuple[float, float, float]) -> int:
        key = (round(position[0], 4), round(position[1], 4), round(position[2], 4))
        index = self._position_index.get(key)
        if index is None:
            index = len(self.positions)
            self._position_index[key] = index
            self.positions.append(key)
        return index

    def _normal(self, normal: tuple[float, float, float]) -> int:
        key = (round(normal[0], 5), round(normal[1], 5), round(normal[2], 5))
        index = self._normal_index.get(key)
        if index is None:
            index = len(self.normals)
            self._normal_index[key] = index
            self.normals.append(key)
        return index

    @property
    def triangle_count(self) -> int:
        """Number of triangles in the mesh."""
        return len(self.triangles)

    def bounds_z(self) -> tuple[float, float]:
        """Return ``(min_z, max_z)`` over all vertices."""
        if not self.positions:
            return (0.0, 0.0)
        zs = [p[2] for p in self.positions]
        return (min(zs), max(zs))


def _round3(p: tuple[float, float, float]) -> tuple[float, float, float]:
    """Round a position the way the mesh stores it."""
    return (round(p[0], 4), round(p[1], 4), round(p[2], 4))


def _centre(values: NDArray[np.float64]) -> float:
    """Return the midpoint of a coordinate range.

    Deliberately not the mean: a closed ring repeats its first vertex, so a mean
    is biased towards that corner and the mesh drifts off centre. The bounding-box
    midpoint is exactly what an instance transform needs.
    """
    return float((values.min() + values.max()) / 2.0)


def _face_normal(
    a: tuple[float, float, float],
    b: tuple[float, float, float],
    c: tuple[float, float, float],
) -> tuple[float, float, float] | None:
    """Return the unit normal of a triangle, or ``None`` if it is degenerate."""
    ux, uy, uz = b[0] - a[0], b[1] - a[1], b[2] - a[2]
    vx, vy, vz = c[0] - a[0], c[1] - a[1], c[2] - a[2]
    nx = uy * vz - uz * vy
    ny = uz * vx - ux * vz
    nz = ux * vy - uy * vx
    length = math.sqrt(nx * nx + ny * ny + nz * nz)
    if length < 1e-12:
        return None
    return (nx / length, ny / length, nz / length)


def roof_height_for(ring: NDArray[np.float64], klass_roof: str) -> float:
    """Return a plausible roof height for a footprint.

    Args:
        ring: Closed ``(n, 2)`` ring in metres.
        klass_roof: ``"flat"``, ``"gable"`` or ``"hip"``.

    Returns:
        Roof height in metres; ``0`` for a flat roof.
    """
    if klass_roof == "flat":
        return 0.0
    xs = ring[:, 0]
    ys = ring[:, 1]
    depth = min(float(xs.max() - xs.min()), float(ys.max() - ys.min()))
    return float(np.clip(depth * _ROOF_PITCH, _MIN_ROOF_M, _MAX_ROOF_M))


def extrude_footprint(
    ring: NDArray[np.float64],
    *,
    height_m: float,
    roof: str = "gable",
    roof_height_m: float | None = None,
) -> Mesh:
    """Build a closed building mesh from a footprint.

    The mesh is centred on the footprint's centroid in X/Y with ``z = 0`` at
    ground level, so a ``TSStatic`` at ``position = (centroid_x, centroid_y,
    ground_z)`` places it without rotation.

    Args:
        ring: Closed ``(n, 2)`` ring in world metres, counter-clockwise.
        height_m: Wall height above ground in metres.
        roof: ``"flat"``, ``"gable"`` or ``"hip"``.
        roof_height_m: Explicit roof height; derived from the footprint when
            ``None``.

    Returns:
        The generated :class:`Mesh`.

    Raises:
        ValueError: If the ring is not a usable closed polygon or the height is
            not positive.
    """
    if height_m <= 0:
        raise ValueError(f"height_m must be positive, got {height_m}")
    if ring.shape[0] < 4:
        raise ValueError(f"ring must be a closed polygon with >= 4 points, got {ring.shape[0]}")

    polygon = Polygon(ring)
    if not polygon.is_valid or polygon.area <= 0:
        raise ValueError("ring does not describe a valid polygon")

    # Ensure counter-clockwise winding so wall normals always point outwards,
    # even when the caller passes a clockwise OSM way ring directly.
    signed_area = float(0.5 * np.sum(ring[:-1, 0] * ring[1:, 1] - ring[1:, 0] * ring[:-1, 1]))
    if signed_area < 0:
        ring = ring[::-1].copy()

    centre_x = _centre(ring[:, 0])
    centre_y = _centre(ring[:, 1])
    local = ring - np.array([centre_x, centre_y], dtype=np.float64)

    # Align the roof ridge with the footprint's longest edge by working in a
    # rotated frame, then rotate the result back so the mesh needs no transform.
    angle = _principal_angle(local)
    cos_a, sin_a = math.cos(-angle), math.sin(-angle)
    rotation = np.array([[cos_a, -sin_a], [sin_a, cos_a]], dtype=np.float64)
    aligned = local @ rotation.T

    mesh = Mesh()
    _build_extruded_body(mesh, aligned, height_m, roof, roof_height_m)

    # Rotate positions and normals back into world-aligned local coordinates.
    back = np.array([[math.cos(angle), -math.sin(angle)], [math.sin(angle), math.cos(angle)]])
    rotated_positions = []
    for x, y, z in mesh.positions:
        wx, wy = back @ np.array([x, y], dtype=np.float64)
        rotated_positions.append((round(float(wx), 4), round(float(wy), 4), z))
    mesh.positions = rotated_positions
    mesh._position_index = {p: i for i, p in enumerate(rotated_positions)}

    rotated_normals = []
    for nx, ny, nz in mesh.normals:
        wnx, wny = back @ np.array([nx, ny], dtype=np.float64)
        rotated_normals.append((round(float(wnx), 5), round(float(wny), 5), nz))
    mesh.normals = rotated_normals
    mesh._normal_index = {n: i for i, n in enumerate(rotated_normals)}
    return mesh


def _principal_angle(ring: NDArray[np.float64]) -> float:
    """Return the orientation of the ring's longest edge, in radians."""
    deltas = np.diff(ring, axis=0)
    if deltas.size == 0:
        return 0.0
    lengths = np.hypot(deltas[:, 0], deltas[:, 1])
    longest = int(np.argmax(lengths))
    return math.atan2(float(deltas[longest, 1]), float(deltas[longest, 0]))


def _split_ring_at_y(ring: NDArray[np.float64], cut_y: float) -> NDArray[np.float64]:
    """Insert vertices where any ring edge crosses ``y = cut_y``."""
    out: list[tuple[float, float]] = []
    n = ring.shape[0] - 1
    for i in range(n):
        x0, y0 = float(ring[i, 0]), float(ring[i, 1])
        x1, y1 = float(ring[i + 1, 0]), float(ring[i + 1, 1])
        out.append((x0, y0))
        if (y0 - cut_y) * (y1 - cut_y) < 0.0 and abs(y1 - y0) > 1e-12:
            t = (cut_y - y0) / (y1 - y0)
            out.append((x0 + t * (x1 - x0), cut_y))
    out.append(out[0])
    return np.asarray(out, dtype=np.float64)


def _add_walls(
    mesh: Mesh,
    ring: NDArray[np.float64],
    height_m: float,
    top_z: Callable[[float, float], float] | None = None,
) -> None:
    """Add extruded wall quads (plus gable pediments when ``top_z`` varies)."""
    n = ring.shape[0] - 1  # the ring is closed, so the last point repeats the first
    for i in range(n):
        x0, y0 = float(ring[i, 0]), float(ring[i, 1])
        x1, y1 = float(ring[i + 1, 0]), float(ring[i + 1, 1])
        dx, dy = x1 - x0, y1 - y0
        if math.hypot(dx, dy) < 1e-9:
            continue
        z0 = height_m if top_z is None else top_z(x0, y0)
        z1 = height_m if top_z is None else top_z(x1, y1)
        # Winding alone determines the normal: with a counter-clockwise ring,
        # (bottom0, bottom1, top1) yields the outward normal (dy, -dx) / |d|.
        bottom0 = (x0, y0, 0.0)
        bottom1 = (x1, y1, 0.0)
        top0 = (x0, y0, z0)
        top1 = (x1, y1, z1)
        mesh.add_triangle(bottom0, bottom1, top1)
        mesh.add_triangle(bottom0, top1, top0)


def _iter_polygons(geom: object) -> list[Polygon]:
    """Extract valid non-empty Polygon parts from any Shapely geometry."""
    if isinstance(geom, Polygon):
        return [geom] if not geom.is_empty and geom.area > 1e-9 else []
    geoms = getattr(geom, "geoms", None)
    if geoms is None:
        return []
    result: list[Polygon] = []
    for sub in geoms:
        result.extend(_iter_polygons(sub))
    return result


def _emit_triangulated_polygons(
    mesh: Mesh,
    polygons: list[Polygon],
    lift: Callable[[float, float], float],
    *,
    up: bool = True,
) -> None:
    """Constrained-Delaunay triangulate polygons and emit oriented faces."""
    for poly in polygons:
        collection = constrained_delaunay_triangles(poly)
        for triangle in _iter_polygons(collection):
            coords = list(triangle.exterior.coords)[:3]
            pts = [(float(p[0]), float(p[1])) for p in coords]
            area2 = (
                (pts[1][0] - pts[0][0]) * (pts[2][1] - pts[0][1])
                - (pts[2][0] - pts[0][0]) * (pts[1][1] - pts[0][1])
            )
            if abs(area2) < 1e-9:
                continue
            order = pts if (area2 > 0) == up else pts[::-1]
            mesh.add_triangle(
                (order[0][0], order[0][1], lift(*order[0])),
                (order[1][0], order[1][1], lift(*order[1])),
                (order[2][0], order[2][1], lift(*order[2])),
            )


def _build_extruded_body(
    mesh: Mesh,
    ring: NDArray[np.float64],
    height_m: float,
    roof: str,
    roof_height_m: float | None,
) -> None:
    """Build walls, roof and ground cap in the ridge-aligned local frame."""
    if roof == "flat" or (roof_height_m is not None and roof_height_m <= 0):
        _add_walls(mesh, ring, height_m)
        _add_flat_cap(mesh, ring, height_m, up=True)
        _add_flat_cap(mesh, ring, 0.0, up=False)
        return

    roof_height = (
        roof_height_for(ring, roof) if roof_height_m is None else max(0.0, roof_height_m)
    )
    if roof_height <= 0:
        _add_walls(mesh, ring, height_m)
        _add_flat_cap(mesh, ring, height_m, up=True)
        _add_flat_cap(mesh, ring, 0.0, up=False)
        return

    polygon = Polygon(ring)
    xs = ring[:, 0]
    ys = ring[:, 1]
    centre_x = _centre(xs)
    centre_y = _centre(ys)
    half_x = max(1e-6, float(np.abs(xs - centre_x).max()))
    half_y = max(1e-6, float(np.abs(ys - centre_y).max()))
    minx, miny, maxx, maxy = polygon.bounds

    if roof == "hip":
        # Perimeter eaves stay level at height_m; interior ridge vertices rise
        # to height_m + roof_height while concave edges stay watertight.
        _add_walls(mesh, ring, height_m)
        _add_flat_cap(mesh, ring, 0.0, up=False)

        ridge_half = max(0.0, half_x - half_y)
        candidates = (
            [(centre_x - ridge_half, centre_y), (centre_x, centre_y), (centre_x + ridge_half, centre_y)]
            if ridge_half > 1e-3
            else [(centre_x, centre_y)]
        )
        ridge_pts = [
            pt
            for pt in candidates
            if polygon.contains(Point(pt)) and polygon.exterior.distance(Point(pt)) > 1e-3
        ]
        if not ridge_pts:
            rep = polygon.representative_point()
            ridge_pts = [(float(rep.x), float(rep.y))]

        max_dist = max(1e-6, max(polygon.exterior.distance(Point(pt)) for pt in ridge_pts))
        cut_ys = sorted({miny - 1.0, *(pt[1] for pt in ridge_pts), maxy + 1.0})
        cut_xs = sorted({minx - 1.0, *(pt[0] for pt in ridge_pts), maxx + 1.0})
        cells: list[Polygon] = []
        for ix in range(len(cut_xs) - 1):
            for iy in range(len(cut_ys) - 1):
                clipped = polygon.intersection(box(cut_xs[ix], cut_ys[iy], cut_xs[ix + 1], cut_ys[iy + 1]))
                cells.extend(_iter_polygons(clipped))

        def lift_hip(x: float, y: float) -> float:
            d = polygon.exterior.distance(Point(x, y))
            if d < 1e-6:
                return height_m
            return height_m + roof_height * min(1.0, d / max_dist)

        _emit_triangulated_polygons(mesh, cells, lift_hip, up=True)
        return

    # Gable roof: split along the ridge line y = centre_y so the ridge exists as
    # real geometry and gable end walls rise smoothly to meet the peak.
    def lift_gable(x: float, y: float) -> float:
        _ = x
        t = abs(y - centre_y) / half_y
        return height_m + roof_height * (1.0 - min(1.0, t))

    split_ring = _split_ring_at_y(ring, centre_y)
    _add_walls(mesh, split_ring, height_m, top_z=lift_gable)
    _add_flat_cap(mesh, split_ring, 0.0, up=False)

    north = polygon.intersection(box(minx - 1.0, centre_y, maxx + 1.0, maxy + 1.0))
    south = polygon.intersection(box(minx - 1.0, miny - 1.0, maxx + 1.0, centre_y))
    _emit_triangulated_polygons(mesh, _iter_polygons(north) + _iter_polygons(south), lift_gable, up=True)


def _add_flat_cap(
    mesh: Mesh,
    ring: NDArray[np.float64],
    z: float,
    *,
    up: bool,
) -> None:
    """Triangulate the footprint into a horizontal cap at height ``z``."""
    polygon = Polygon(ring)
    _emit_triangulated_polygons(mesh, _iter_polygons(polygon), lambda _x, _y: z, up=up)


